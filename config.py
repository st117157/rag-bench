"""Все настройки проекта в одном месте.

Правило: ни одного «магического числа» в остальном коде.
Размер чанка, модель, пороги — всё меняется здесь.
Для бенчмарка это критично: иначе через неделю уже не восстановить,
с какими параметрами получены цифры в таблице.
"""

import os
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

# --- пути ---
ROOT = Path(__file__).parent
CORPUS_DIR = ROOT / "data" / "corpus"      # сюда скачается документация
INDEX_DIR = ROOT / "data" / "index"        # сюда сохранится векторный индекс
RESULTS_DIR = ROOT / "results"             # сюда пишутся результаты прогонов
QUESTIONS_FILE = ROOT / "eval" / "questions.yaml"

# --- модели ---
# Генерация ответа. Модель намеренно дешёвая: прогон — это сотни вызовов.
LLM_MODEL = "gpt-4o-mini"
LLM_BASE_URL = os.getenv("OPENAI_BASE_URL")  # None = обычный OpenAI

# Эмбеддинги. Это локальная модель, денег не стоит, качается один раз (~130 МБ).
EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"

# Реранкер — cross-encoder. Тоже локальный, ~80 МБ.
# Он медленнее эмбеддингов, поэтому применяется только к топ-N кандидатам.
RERANKER_MODEL = "cross-encoder/ms-marco-MiniLM-L-6-v2"

# --- параметры чанкования ---
# "markdown" — резать по заголовкам, сохраняя структуру документа.
# "chars"    — наивная нарезка по символам, как в туториалах.
# Переключение стратегии и повторный прогон — самый дешёвый способ
# измерить, насколько препроцессинг важнее выбора векторной базы.
CHUNK_STRATEGY = "markdown"

CHUNK_SIZE = 800        # максимум символов в чанке
CHUNK_OVERLAP = 150     # нахлёст, используется только стратегией "chars"

# --- параметры поиска ---
TOP_K = 5               # сколько чанков уходит в промпт модели
CANDIDATES_K = 20       # сколько кандидатов достаём ДО реранкинга

# Вес плотного (векторного) поиска при слиянии с BM25 в гибриде.
# 1.0 — только вектора, 0.0 — только слова, 0.5 — поровну.
# Значение подобрано перебором (scripts/04_sweep_alpha.py): на этом корпусе
# оптимум смещён к векторам, потому что доля семантических вопросов велика,
# а BM25 на них даёт нулевой recall. На другом наборе вопросов оптимум
# окажется другим — перебор стоит повторить.
HYBRID_ALPHA = 0.8

# Пороги честного отказа, по одному на подход.
#
# Cross-encoder выдаёт АБСОЛЮТНЫЙ скор релевантности (в отличие от косинуса,
# который относителен), поэтому его можно сравнивать с порогом: лучший
# кандидат ниже порога — значит ответа в корпусе нет, и честнее промолчать,
# чем сочинять.
#
# Почему пороги РАЗНЫЕ у разных подходов. Оценка берётся как максимум
# по отобранным кандидатам, а их число различается: reranked смотрит
# на CANDIDATES_K штук, hybrid_gated — только на TOP_K. Максимум по двадцати
# кандидатам систематически выше максимума по пяти, поэтому одно и то же
# число означает у них разную степень уверенности. Общий порог сместил бы
# один из подходов с его оптимума.
#
# None — механизм для этого подхода выключен.
# Подобрать значения: python scripts/05_analyze_abstention.py --method <имя>
ABSTAIN_THRESHOLDS: dict[str, float | None] = {
    "reranked": 0.0,
    "hybrid_gated": -3.0,
    "grep": None,
}

# --- цены (USD за 1 млн токенов), для подсчёта стоимости ---
