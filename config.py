PRICE_PER_1M_INPUT = 0.15
PRICE_PER_1M_OUTPUT = 0.60

# --- long-context ветка ---
# Сколько токенов максимум кладём в промпт.
MAX_CONTEXT_TOKENS = 100_000

# Сколько файлов отбирает LongContextFiltered перед тем,
# как подать их целиком. Больше файлов — выше recall и цена.
LONGCTX_FILES = 8
